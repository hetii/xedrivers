#!/usr/bin/env python3
"""Take what src/drivers/rtw8822b needs verbatim from Linux's rtw88 (GPL-2.0 OR
BSD-3-Clause, Realtek): the register names (reg.h) and the chip's initialisation
tables (rtw8822b_table.c), turned into plain C this build compiles. Nothing is
edited by hand afterwards; run it again against a newer rtw88 to refresh them.

    tools/rtw88_import.py RTW88_DIR SRC_DIR

RTW88_DIR is drivers/net/wireless/realtek/rtw88 of a Linux tree, SRC_DIR is
src/drivers/rtw8822b. The Linux commit is written into each file's header.
"""

import os
import re
import subprocess
import sys

rtw, out = sys.argv[1], sys.argv[2]
try:
    rev = subprocess.run(["git", "-C", rtw, "log", "-1", "--format=%h %cs"],
                         capture_output=True, text=True).stdout.strip()
except OSError:
    rev = ""
rev = rev or os.environ.get("RTW88_REV", "unknown")   # a tree that is not a checkout

HEAD = ("/* Generated by tools/rtw88_import.py from Linux's rtw88 (%s, commit %s);\n"
        " * do not edit. Copyright(c) 2018-2019 Realtek Corporation, licensed\n"
        " * GPL-2.0 OR BSD-3-Clause, used here under BSD-3-Clause. */\n\n")

# reg.h: every #define, as it is, with BIT and GENMASK given.
src = open(os.path.join(rtw, "reg.h")).read()
lines = [l for l in src.splitlines()
         if not l.startswith("// SPDX") and "#include" not in l]
body = "\n".join(lines).replace("__RTW_REG_H__", "XE_RTW_REG_H")
with open(os.path.join(out, "rtw_reg.h"), "w") as f:
    f.write(HEAD % ("reg.h", rev))
    f.write("#ifndef BIT\n#define BIT(n) (1u << (n))\n#endif\n")
    f.write("#ifndef GENMASK\n#define GENMASK(h, l) "
            "((~0u << (l)) & (~0u >> (31 - (h))))\n#endif\n\n")
    f.write(body.strip() + "\n")

# rtw8822b_table.c: the u32 arrays, each with its length; the declarations that
# bind them to rtw88's parsers are replaced by RTW_TABLE entries.
src = open(os.path.join(rtw, "rtw8822b_table.c")).read()
arrays = re.findall(r"static const u32 (\w+)\[\] = \{(.*?)\};", src, re.S)
with open(os.path.join(out, "tables", "rtw8822b_table.c"), "w") as f:   # packed, not built in (Makefile)
    f.write(HEAD % ("rtw8822b_table.c", rev))
    f.write('#include "rtw8822b_table.h"\n\n')
    for name, data in arrays:
        f.write("static const u32 %s[] = {%s};\n\n" % (name, data))
        f.write("const RTW_TABLE %s_tbl = { %s, sizeof(%s) / sizeof(%s[0]) };\n\n"
                % (name, name, name, name))
with open(os.path.join(out, "rtw8822b_table.h"), "w") as f:
    f.write(HEAD % ("rtw8822b_table.c", rev))
    f.write("#ifndef XE_RTW8822B_TABLE_H\n#define XE_RTW8822B_TABLE_H\n\n")
    f.write('#include "kernel.h"\n\n')
    f.write("typedef struct {\n    const u32 *data;\n    u32 size;           /* words */\n"
            "} RTW_TABLE;\n\n")
    for name, _ in arrays:
        f.write("extern const RTW_TABLE %s_tbl;\n" % name)
    f.write("\n#endif\n")
# rtw8822b.c's power sequences: the command arrays and the two flows, with the
# constants they use from main.h.
src = open(os.path.join(rtw, "rtw8822b.c")).read()
seqs = re.findall(r"static const struct rtw_pwr_seq_cmd (\w+)\[\] = \{(.*?)\n\};", src, re.S)
flows = re.findall(r"static const struct rtw_pwr_seq_cmd \* const (\w+)\[\] = \{(.*?)\};",
                   src, re.S)
main_h = open(os.path.join(rtw, "main.h")).read()
consts = re.findall(r"^#define (RTW_PWR_(?:CMD|ADDR|INTF|CUT)_\w+)\s+(.+)$", main_h, re.M)
with open(os.path.join(out, "rtw8822b_pwrseq.c"), "w") as f:
    f.write(HEAD % ("rtw8822b.c", rev))
    f.write('#include "rtw8822b_table.h"\n#include "rtw_reg.h"\n\n')
    for name, value in consts:
        f.write("#define %s %s\n" % (name, value))
    f.write("#define RTW_PWR_DELAY_US 0\n#define RTW_PWR_DELAY_MS 1\n")
    f.write("#ifndef NULL\n#define NULL ((void *)0)\n#endif\n\n")
    for name, data in seqs:
        f.write("static const RTW_PWR_CMD %s[] = {%s\n};\n\n" % (name, data))
    for name, data in flows:
        f.write("const RTW_PWR_CMD *const %s[] = {%s};\n\n" % (name, data))
with open(os.path.join(out, "rtw8822b_table.h"), "a") as f:
    pass
h = open(os.path.join(out, "rtw8822b_table.h")).read()
h = h.replace("\n#endif\n", """
/* One step of a power sequence, rtw88's struct rtw_pwr_seq_cmd: write `value`
 * under `mask` to the byte at `offset`, poll for it, or wait. */
typedef struct {
    u16 offset;
    u8  cut_mask;
    u8  intf_mask;
    u8  base;               /* RTW_PWR_ADDR_* */
    u8  cmd;                /* RTW_PWR_CMD_* */
    u8  mask;
    u8  value;
} RTW_PWR_CMD;

""" + "".join("extern const RTW_PWR_CMD *const %s[];\n" % n for n, _ in flows) + "\n#endif\n")
open(os.path.join(out, "rtw8822b_table.h"), "w").write(h)
# The constants rtw8822b.c, rtw8822b.h and mac.h define for themselves: plain
# values and expressions of them, continuation lines kept; macros that take
# arguments or reach into the driver's structures are left out.
def defines(text):
    out = []
    lines = text.split("\n")
    i = 0
    while i < len(lines):
        l = lines[i]
        if l.startswith("#define "):
            block = [l]
            while block[-1].rstrip().endswith("\\") and i + 1 < len(lines):
                i += 1
                block.append(lines[i])
            name = l.split()[1]
            body = "\n".join(block)
            if "(" not in name and "rtwdev" not in body and "struct" not in body:
                out.append(body)
        i += 1
    return out

defs = []
for fn in ("mac.h", "bf.h", "rtw8822b.h", "rtw8822b.c"):
    for d in defines(open(os.path.join(rtw, fn)).read()):
        if not re.match(r"#define (__|_RTW|RTW8822B_H)", d):
            defs.append((fn, d))
with open(os.path.join(out, "rtw8822b_defs.h"), "w") as f:
    f.write(HEAD % ("mac.h, bf.h, rtw8822b.h and rtw8822b.c", rev))
    f.write("#ifndef XE_RTW8822B_DEFS_H\n#define XE_RTW8822B_DEFS_H\n\n")
    f.write('#include "rtw_reg.h"\n\n')
    last = None
    for fn, d in defs:
        if fn != last:
            f.write("/* %s */\n" % fn)
            last = fn
        f.write(d + "\n")
    f.write("\n#endif\n")
print("%d tables, %d power sequences in %d flows, reg.h %d lines, from %s"
      % (len(arrays), len(seqs), len(flows), len(lines), rev))
print("%d constants" % len(defs))

# The transmit power by rate (rtw8822b_table.c's bb_pg tables, one per RFE type the
# chip's rfe_defs name), as rtw88 turns them into offsets: phy.c's
# rtw_phy_get_rate_values_of_txpwr_by_rate says which rates a register's bytes are
# (read out of that function here), the bytes are BCD (is_pwr_by_rate_dec), and
# rtw_phy_tx_power_by_rate_config makes each rate relative to its section's base.
# Out: rtw8822b_txpwr_by_rate[type][band 2G/5G][path A/B][DESC rate 0-0x3f].
mainh = open(os.path.join(rtw, "main.h")).read()
desc = {m.group(1): int(m.group(2), 16)
        for m in re.finditer(r"(DESC_RATE\w+)\s*=\s*(0x[0-9a-fA-F]+)", mainh)}
phy = open(os.path.join(rtw, "phy.c")).read()
fn = phy[phy.index("rtw_phy_get_rate_values_of_txpwr_by_rate(struct"):]
fn = fn[fn.index("switch (addr)"):fn.index("\n}\n")]
rate_map = {}                               # (addr, mask or None) -> [(rate, byte)]
for block in re.split(r"\n\t\tbreak;", fn):
    addrs = [int(a, 16) for a in re.findall(r"case (0x[0-9A-Fa-f]+):", block)]
    if not addrs:
        continue
    variants = re.split(r"\} else if|\bif \(mask", block) if "mask ==" in block else [block]
    for v in variants:
        rates = [desc[r] for r in re.findall(r"rate\[\d\] = (DESC_RATE\w+);", v)]
        if not rates:
            continue
        mask = re.search(r"mask == (0x[0-9a-f]+)", v)
        first = re.search(r"for \(i = (\d);", v)
        single = re.search(r"bcd_to_dec_pwr_by_rate\(val, (\d)\)", v)
        start = int(first.group(1)) if first else int(single.group(1)) if single else 0
        key = int(mask.group(1), 16) if mask else None
        for a in addrs:
            rate_map[(a, key)] = [(r, start + i) for i, r in enumerate(rates)]

def bcd(b):
    return (b >> 4) * 10 + (b & 15)

table = open(os.path.join(rtw, "rtw8822b_table.c")).read()
chip = open(os.path.join(rtw, "rtw8822b.c")).read()
types = sorted({int(t) for t in re.findall(r"RTW_DEF_RFE\(8822b, (\d+),", chip)})
rfe_type = {int(r): int(t) for r, t in re.findall(r"\[(\d+)\] = RTW_DEF_RFE\(8822b, (\d+),", chip)}
sections = [list(range(0, 4)), list(range(4, 12)), list(range(0x0C, 0x14)),
            list(range(0x14, 0x1C)), list(range(0x2C, 0x36)), list(range(0x36, 0x40))]
power = {}
for t in types:
    m = re.search(r"rtw8822b_bb_pg_type%d\[\] = \{(.*?)\n\};" % t, table, re.S)
    off = [[[0] * 64 for _ in range(2)] for _ in range(2)]
    for e in re.findall(r"\{([^{}]*)\}", m.group(1)):
        band, path, _, addr, mask, data = [int(x, 0) for x in e.replace(" ", "").strip(",").split(",")]
        if addr in (0xFE, 0xFFE) or path > 1:
            continue
        rates = rate_map.get((addr, mask)) or rate_map.get((addr, None))
        for r, byte in rates or []:
            if r < 64:
                off[band][path][r] = bcd((data >> (byte * 8)) & 0xFF)
    for band in range(2):
        for path in range(2):
            for s in sections:
                base = off[band][path][s[-3] if len(s) == 10 else s[-1]]
                for r in s:
                    off[band][path][r] -= base
    power[t] = off
with open(os.path.join(out, "rtw8822b_txpwr.c"), "w") as f:
    f.write(HEAD % ("phy.c and rtw8822b_table.c", rev))
    f.write('#include "rtw8822b_txpwr.h"\n\n')
    f.write("const s8 rtw8822b_txpwr_by_rate[RTW8822B_PG_TYPES][2][2][64] = {\n")
    for t in types:
        f.write("    {   /* bb_pg_type%d */\n" % t)
        for band in range(2):
            f.write("        {\n")
            for path in range(2):
                v = power[t][band][path]
                f.write("            {" + ", ".join(str(x) for x in v) + "},\n")
            f.write("        },\n")
        f.write("    },\n")
    f.write("};\n\n/* the table of each RFE option, or -1 */\n")
    f.write("const s8 rtw8822b_txpwr_type_of_rfe[RTW8822B_RFE_MAX] = {")
    f.write(", ".join(str(types.index(rfe_type[r]) if r in rfe_type else -1)
                      for r in range(max(rfe_type) + 1)))
    f.write("};\n")
with open(os.path.join(out, "rtw8822b_txpwr.h"), "w") as f:
    f.write(HEAD % ("phy.c and rtw8822b_table.c", rev))
    f.write("#ifndef XE_RTW8822B_TXPWR_H\n#define XE_RTW8822B_TXPWR_H\n\n")
    f.write('#include "kernel.h"\n\n')
    f.write("#define RTW8822B_PG_TYPES %d\n#define RTW8822B_RFE_MAX %d\n\n" % (len(types), max(rfe_type) + 1))
    f.write("extern const s8 rtw8822b_txpwr_by_rate[RTW8822B_PG_TYPES][2][2][64];\n")
    f.write("extern const s8 rtw8822b_txpwr_type_of_rfe[RTW8822B_RFE_MAX];\n\n#endif\n")
print("transmit power by rate: types %s, %d register layouts" % (types, len(rate_map)))

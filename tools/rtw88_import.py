#!/usr/bin/env python3
"""Take what src/drivers/rtw8822b needs verbatim from Linux's rtw88 (GPL-2.0 OR
BSD-3-Clause, Realtek): the register names (reg.h) and the chip's initialisation
tables (rtw8822b_table.c), turned into plain C this build compiles. Nothing is
edited by hand afterwards; run it again against a newer rtw88 to refresh them.

    tools/rtw88_import.py RTW88_DIR SRC_DIR

RTW88_DIR is drivers/net/wireless/realtek/rtw88 of a Linux tree, SRC_DIR is
src/drivers/rtw8822b. The Linux commit is written into each file's header.
"""

import os
import re
import subprocess
import sys

rtw, out = sys.argv[1], sys.argv[2]
try:
    rev = subprocess.run(["git", "-C", rtw, "log", "-1", "--format=%h %cs"],
                         capture_output=True, text=True).stdout.strip()
except OSError:
    rev = "unknown"

HEAD = ("/* Generated by tools/rtw88_import.py from Linux's rtw88 (%s, commit %s);\n"
        " * do not edit. Copyright(c) 2018-2019 Realtek Corporation, licensed\n"
        " * GPL-2.0 OR BSD-3-Clause, used here under BSD-3-Clause. */\n\n")

# reg.h: every #define, as it is, with BIT and GENMASK given.
src = open(os.path.join(rtw, "reg.h")).read()
lines = [l for l in src.splitlines()
         if not l.startswith("// SPDX") and "#include" not in l]
body = "\n".join(lines).replace("__RTW_REG_H__", "XE_RTW_REG_H")
with open(os.path.join(out, "rtw_reg.h"), "w") as f:
    f.write(HEAD % ("reg.h", rev))
    f.write("#ifndef BIT\n#define BIT(n) (1u << (n))\n#endif\n")
    f.write("#ifndef GENMASK\n#define GENMASK(h, l) "
            "((~0u << (l)) & (~0u >> (31 - (h))))\n#endif\n\n")
    f.write(body.strip() + "\n")

# rtw8822b_table.c: the u32 arrays, each with its length; the declarations that
# bind them to rtw88's parsers are replaced by RTW_TABLE entries.
src = open(os.path.join(rtw, "rtw8822b_table.c")).read()
arrays = re.findall(r"static const u32 (\w+)\[\] = \{(.*?)\};", src, re.S)
with open(os.path.join(out, "rtw8822b_table.c"), "w") as f:
    f.write(HEAD % ("rtw8822b_table.c", rev))
    f.write('#include "rtw8822b_table.h"\n\n')
    for name, data in arrays:
        f.write("static const u32 %s[] = {%s};\n\n" % (name, data))
        f.write("const RTW_TABLE %s_tbl = { %s, sizeof(%s) / sizeof(%s[0]) };\n\n"
                % (name, name, name, name))
with open(os.path.join(out, "rtw8822b_table.h"), "w") as f:
    f.write(HEAD % ("rtw8822b_table.c", rev))
    f.write("#ifndef XE_RTW8822B_TABLE_H\n#define XE_RTW8822B_TABLE_H\n\n")
    f.write('#include "kernel.h"\n\n')
    f.write("typedef struct {\n    const u32 *data;\n    u32 size;           /* words */\n"
            "} RTW_TABLE;\n\n")
    for name, _ in arrays:
        f.write("extern const RTW_TABLE %s_tbl;\n" % name)
    f.write("\n#endif\n")
# rtw8822b.c's power sequences: the command arrays and the two flows, with the
# constants they use from main.h.
src = open(os.path.join(rtw, "rtw8822b.c")).read()
seqs = re.findall(r"static const struct rtw_pwr_seq_cmd (\w+)\[\] = \{(.*?)\n\};", src, re.S)
flows = re.findall(r"static const struct rtw_pwr_seq_cmd \* const (\w+)\[\] = \{(.*?)\};",
                   src, re.S)
main_h = open(os.path.join(rtw, "main.h")).read()
consts = re.findall(r"^#define (RTW_PWR_(?:CMD|ADDR|INTF|CUT)_\w+)\s+(.+)$", main_h, re.M)
with open(os.path.join(out, "rtw8822b_pwrseq.c"), "w") as f:
    f.write(HEAD % ("rtw8822b.c", rev))
    f.write('#include "rtw8822b_table.h"\n#include "rtw_reg.h"\n\n')
    for name, value in consts:
        f.write("#define %s %s\n" % (name, value))
    f.write("#define RTW_PWR_DELAY_US 0\n#define RTW_PWR_DELAY_MS 1\n")
    f.write("#ifndef NULL\n#define NULL ((void *)0)\n#endif\n\n")
    for name, data in seqs:
        f.write("static const RTW_PWR_CMD %s[] = {%s\n};\n\n" % (name, data))
    for name, data in flows:
        f.write("const RTW_PWR_CMD *const %s[] = {%s};\n\n" % (name, data))
with open(os.path.join(out, "rtw8822b_table.h"), "a") as f:
    pass
h = open(os.path.join(out, "rtw8822b_table.h")).read()
h = h.replace("\n#endif\n", """
/* One step of a power sequence, rtw88's struct rtw_pwr_seq_cmd: write `value`
 * under `mask` to the byte at `offset`, poll for it, or wait. */
typedef struct {
    u16 offset;
    u8  cut_mask;
    u8  intf_mask;
    u8  base;               /* RTW_PWR_ADDR_* */
    u8  cmd;                /* RTW_PWR_CMD_* */
    u8  mask;
    u8  value;
} RTW_PWR_CMD;

""" + "".join("extern const RTW_PWR_CMD *const %s[];\n" % n for n, _ in flows) + "\n#endif\n")
open(os.path.join(out, "rtw8822b_table.h"), "w").write(h)
print("%d tables, %d power sequences in %d flows, reg.h %d lines, from %s"
      % (len(arrays), len(seqs), len(flows), len(lines), rev))

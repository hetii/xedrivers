/* The one interface between the core and a card driver.
 *
 * A driver lives in its own directory under src/drivers/ and defines exactly one
 * global, `const XE_DRIVER xe_driver_<directory>`. The Makefile lists the
 * directories it builds (DRIVERS=, all of them by default) and generates the table
 * below from them, so adding a card is adding a directory and removing one is
 * deleting it: nothing outside it names the driver.
 *
 * A driver may build on another's public header -- rtl8156 is the CDC driver plus
 * what only a Realtek answers -- and that include is the whole of the dependency:
 * a build without the other driver stops there.
 *
 * The core owns up to USB_MAX_DEVICES devices at once. When the kernel offers one,
 * every driver's `match` is asked and the highest score takes it; the network
 * layer then calls `start` from the worker thread with that device's NET_DEV,
 * routes frames to `xmit` while it is the uplink, and calls `detached` when it
 * goes. Frames, link state and buffers go back up through net.h, each call naming
 * its device.
 */

#ifndef XE_DRIVER_H
#define XE_DRIVER_H

#include "kernel.h"

/* How well a driver fits a device. 0 is not at all. */
#define XE_MATCH_NONE   0u
#define XE_MATCH_CLASS  1u          /* by class codes: any device of the kind */
#define XE_MATCH_VENDOR 2u          /* by VID:PID: this product, its quirks known */

/* What kind of link a driver's device is, for choosing among several with a link
 * up (src/net/net.c). Higher wins: a phone that tethers was plugged in to be used,
 * a USB card over the console's own port. */
#define XE_KIND_AUDIO   0u          /* no network at all: never an uplink, xnet not started */
#define XE_KIND_WIFI    1u          /* a USB Wi-Fi card: still before the onboard port */
#define XE_KIND_WIRED   2u          /* a USB Ethernet card */
#define XE_KIND_TETHER  3u          /* a phone sharing its connection */

struct NET_DEV;

typedef struct XE_DRIVER {
    const char *name;
    u32 kind;                       /* XE_KIND_* */

    /* `device` is the 18-byte device descriptor; `interface` one interface
     * descriptor of the device's current configuration, or 0 when only the device
     * is known (the core's scan of what enumerated before the plugin loaded).
     * Called at any IRQL, must not block or touch the device. */
    u32  (*match)(const u8 *device, const u8 *interface);

    /* Bring `nd`'s device up: configuration, endpoints, MAC into nd->mac, receive
     * running; the driver keeps its own per-device state in nd->priv. Worker
     * thread, PASSIVE_LEVEL; control transfers may be waited for. Returns 0, or the
     * step that failed (the driver's own numbering, kept in the device's stats). */
    u32  (*start)(struct NET_DEV *nd);

    /* The device is going: stop resubmitting. DISPATCH_LEVEL, inside RemoveDevice;
     * the core's close chain completes whatever is still queued. */
    void (*detached)(struct NET_DEV *nd);

    /* Queue one Ethernet frame, length checked by the core. Any IRQL up to
     * DISPATCH. 1 if queued, 0 if dropped (the driver counts its own drops). */
    u32  (*xmit)(struct NET_DEV *nd, const u8 *frame, u32 length);

    /* Whether xmit would take a frame now: a hint for a sender deciding to try. */
    u32  (*tx_space)(struct NET_DEV *nd);

    /* Optional: a command from the host that the core does not know (xectl.py cmd
     * N). Worker thread. `args` is the command block: [1..3] in, [5] result, [7]
     * status. Returns 1 if handled. */
    u32  (*command)(struct NET_DEV *nd, u32 what, volatile u32 *args);

    /* Optional: every worker tick (~33 ms measured, PASSIVE_LEVEL), while the
     * device is up -- for what a driver does later rather than at once. */
    void (*tick)(struct NET_DEV *nd);

    /* Optional: the device is gone and nothing of it runs any more (its endpoints are
     * closed, a worker tick has passed): give back `priv` -- what start took for it, kept
     * in nd->priv. Worker thread, PASSIVE_LEVEL. A driver that takes nothing leaves it 0. */
    void (*release)(void *priv);
} XE_DRIVER;

/* Generated by the Makefile from DRIVERS: build/drivers.generated.c. */
extern const XE_DRIVER *const xe_drivers[];
extern const u32 xe_driver_count;


#endif /* XE_DRIVER_H */

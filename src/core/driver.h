/* The one interface between the core and a card driver.
 *
 * A driver lives in its own directory under src/drivers/ and defines exactly one
 * global, `const XE_DRIVER xe_driver_<directory>`. The Makefile lists the
 * directories it builds (DRIVERS=, all of them by default) and generates the table
 * below from them, so adding a card is adding a directory and removing one is
 * deleting it: nothing outside it names the driver.
 *
 * A driver may build on another's public header -- rtl8156 is the CDC driver plus
 * what only a Realtek answers -- and that include is the whole of the dependency:
 * a build without the other driver stops there.
 *
 * The core owns one device at a time. When the kernel offers a device, every
 * driver's `match` is asked and the highest score takes it; the core then calls
 * `start` from its worker thread, routes frames to `xmit`, and calls `detached` when
 * the device goes. Frames, link state and buffers go back up through net.h.
 */

#ifndef XE_DRIVER_H
#define XE_DRIVER_H

#include "kernel.h"

/* How well a driver fits a device. 0 is not at all. */
#define XE_MATCH_NONE   0u
#define XE_MATCH_CLASS  1u          /* by class codes: any device of the kind */
#define XE_MATCH_VENDOR 2u          /* by VID:PID: this product, its quirks known */

typedef struct XE_DRIVER {
    const char *name;

    /* `device` is the 18-byte device descriptor; `interface` one interface
     * descriptor of the device's current configuration, or 0 when only the device
     * is known (the core's scan of what enumerated before the plugin loaded).
     * Called at any IRQL, must not block or touch the device. */
    u32  (*match)(const u8 *device, const u8 *interface);

    /* Bring the device up: configuration, endpoints, MAC into net_mac, receive
     * running. Worker thread, PASSIVE_LEVEL; control transfers may be waited for.
     * Returns 0, or the step that failed (the driver's own numbering, kept in
     * net_stats.step). */
    u32  (*start)(void);

    /* The device is going: stop resubmitting. DISPATCH_LEVEL, inside RemoveDevice;
     * the core's close chain completes whatever is still queued. */
    void (*detached)(void);

    /* Queue one Ethernet frame, length checked by the core. Any IRQL up to
     * DISPATCH. 1 if queued, 0 if dropped (the driver counts its own drops). */
    u32  (*xmit)(const u8 *frame, u32 length);

    /* Whether xmit would take a frame now: a hint for a sender deciding to try. */
    u32  (*tx_space)(void);

    /* Optional: a command from the host that the core does not know (xectl.py cmd
     * N). Worker thread. `args` is the command block: [1..3] in, [5] result, [7]
     * status. Returns 1 if handled. */
    u32  (*command)(u32 what, volatile u32 *args);
} XE_DRIVER;

/* Generated by the Makefile from DRIVERS: build/drivers.generated.c. */
extern const XE_DRIVER *const xe_drivers[];
extern const u32 xe_driver_count;

/* The driver of the device the core has now, or 0. */
extern const XE_DRIVER *volatile xe_driver;

#endif /* XE_DRIVER_H */

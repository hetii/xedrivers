/* Built and run on the PC by the Makefile: the RTL8822BU's register tables (rtw8822b_table.c,
 * from Linux's rtw88) written as firmware/rtw8822b/rtw8822b_tables.bin, and the header the
 * driver checks that file against. The tables are read once, at the card's start
 * (rtw_phy.c), and not kept in the plugin's memory.
 *
 * The file, big-endian words:
 *   'RTWT', version 1, count, header sum (FNV-1a of the entries)
 *   count entries: kind (0 MAC, 1 BB, 2 AGC, 3 RF A, 4 RF B), offset in bytes, words, sum
 *   the tables' words
 * Usage: pack OUT.bin OUT.h
 */
#include <stdio.h>
#include <stdint.h>
#include <string.h>

typedef uint32_t u32;
typedef uint16_t u16;
typedef uint8_t u8;
#define XE_RTW8822B_TABLE_H             /* the plugin's header needs kernel.h: types here */
typedef struct {
    const u32 *data;
    u32 size;
} RTW_TABLE;
#include "rtw8822b_table.c"

static u32 fnv(u32 h, const u32 *w, u32 n)
{
    u32 i, k;

    for (i = 0; i < n; i++)
        for (k = 0; k < 4; k++) {
            h ^= (w[i] >> (24 - 8 * k)) & 0xFF;
            h *= 16777619u;
        }
    return h;
}

static void put(FILE *f, u32 v)
{
    u8 b[4] = { (u8)(v >> 24), (u8)(v >> 16), (u8)(v >> 8), (u8)v };

    fwrite(b, 1, 4, f);
}

int main(int argc, char **argv)
{
    const RTW_TABLE *t[5] = { &rtw8822b_mac_tbl, &rtw8822b_bb_tbl, &rtw8822b_agc_tbl,
                              &rtw8822b_rf_a_tbl, &rtw8822b_rf_b_tbl };
    u32 entry[5][4], offset = 16 + 5 * 16, sum = 2166136261u, i, k;
    FILE *f, *h;

    if (argc != 3)
        return 2;
    for (i = 0; i < 5; i++) {
        entry[i][0] = i;
        entry[i][1] = offset;
        entry[i][2] = t[i]->size;
        entry[i][3] = fnv(2166136261u, t[i]->data, t[i]->size);
        offset += t[i]->size * 4;
    }
    sum = fnv(sum, &entry[0][0], 5 * 4);
    f = fopen(argv[1], "wb");
    h = fopen(argv[2], "w");
    if (!f || !h)
        return 1;
    put(f, 0x52545754u);                /* 'RTWT' */
    put(f, 1);
    put(f, 5);
    put(f, sum);
    for (i = 0; i < 5; i++)
        for (k = 0; k < 4; k++)
            put(f, entry[i][k]);
    for (i = 0; i < 5; i++)
        for (k = 0; k < t[i]->size; k++)
            put(f, t[i]->data[k]);
    fclose(f);
    fprintf(h, "/* Generated by the Makefile (src/drivers/rtw8822b/tables/pack.c); do not edit. */\n"
               "#define RTW_TABLES_SUM   0x%08Xu   /* FNV-1a of the entries of rtw8822b_tables.bin */\n"
               "#define RTW_TABLES_BYTES %uu\n", sum, offset);
    fclose(h);
    return 0;
}
